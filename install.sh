#!/bin/sh
# omp-board installer: hooks every omp session into the board, and optionally
# runs the board server as a systemd --user service.
#
#   ./install.sh              install the omp hook shim
#   ./install.sh --systemd    ...and install + start the omp-board user service
#   ./install.sh --uninstall  remove the hook shim and the service
set -eu

REPO=$(cd "$(dirname "$0")" && pwd)
HOOK_DIR="$HOME/.omp/agent/hooks/pre"
HOOK="$HOOK_DIR/board.js"
MARK="// omp-board shim"
UNIT_DIR="$HOME/.config/systemd/user"
UNIT="$UNIT_DIR/omp-board.service"

say() { printf '%s\n' "$*"; }
die() { printf 'install.sh: %s\n' "$*" >&2; exit 1; }

if [ "${1:-}" = "--uninstall" ]; then
  if [ -f "$HOOK" ] && grep -q "$MARK" "$HOOK"; then rm -f "$HOOK"; say "removed hook shim $HOOK"; fi
  if [ -f "$UNIT" ]; then
    systemctl --user disable --now omp-board.service 2>/dev/null || true
    rm -f "$UNIT"; systemctl --user daemon-reload 2>/dev/null || true
    say "removed service $UNIT"
  fi
  exit 0
fi

NODE=$(command -v node) || die "node not found (need Node.js >= 18)"
major=$("$NODE" -p 'process.versions.node.split(".")[0]')
[ "$major" -ge 18 ] || die "node $major found; need >= 18"
OMP=$(command -v omp || true)
[ -n "$OMP" ] || say "warning: omp not on PATH; set OMP_BIN for the server so it can launch sessions"

# 1) hook shim: omp loads ~/.omp/agent/hooks/pre/*.js; the shim re-exports the
#    repo's hook so updates to the repo (git pull) take effect with no copy step.
mkdir -p "$HOOK_DIR"
if [ -f "$HOOK" ] && ! grep -q "$MARK" "$HOOK"; then
  # back up OUTSIDE hooks/pre so omp never loads the old copy alongside the shim
  bak="$HOME/.omp/agent/board.js.bak.$(date +%Y%m%d%H%M%S)"; mv "$HOOK" "$bak"; say "existing hook moved to $bak"
fi
url=$("$NODE" -e 'console.log(require("url").pathToFileURL(process.argv[1]).href)' "$REPO/hooks/pre/board.js")
printf '%s -> %s (generated by install.sh)\nexport { default } from "%s";\n' "$MARK" "$REPO" "$url" > "$HOOK"
say "hook shim: $HOOK -> $REPO/hooks/pre/board.js"

# 2) optional user service. systemd --user has a minimal PATH, so the omp and
#    node binaries are pinned to absolute paths here.
if [ "${1:-}" = "--systemd" ]; then
  command -v systemctl >/dev/null || die "systemctl not found; run 'node server.mjs' yourself instead"
  mkdir -p "$UNIT_DIR"
  cat > "$UNIT" <<EOF
[Unit]
Description=omp-board (localhost review board for omp sessions)
After=default.target

[Service]
Type=simple
WorkingDirectory=$REPO
Environment=TODO_BOARD_PORT=${TODO_BOARD_PORT:-8787}
${OMP:+Environment=OMP_BIN=$OMP}
ExecStart=$NODE $REPO/server.mjs
Restart=always
RestartSec=2
# restart the server without killing in-flight 'omp -p' workers it launched
KillMode=process
KillSignal=SIGTERM
TimeoutStopSec=10
NoNewPrivileges=true

[Install]
WantedBy=default.target
EOF
  systemctl --user daemon-reload
  systemctl --user enable --now omp-board.service
  say "service: omp-board.service (systemctl --user status omp-board)"
fi

say ""
say "next:"
[ "${1:-}" = "--systemd" ] || say "  node $REPO/server.mjs            # start the board"
say "  open http://127.0.0.1:${TODO_BOARD_PORT:-8787}        # remote box: ssh -L ${TODO_BOARD_PORT:-8787}:localhost:${TODO_BOARD_PORT:-8787} <host>"
say "  export TODO_BOARD_AUTOSESSION=1   # optional: every new omp session gets its own card"
